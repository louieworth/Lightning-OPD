"""After init, the actor's parameters hold the policy it resumed, not the reference model.

Without colocation (standard OPD, K=120) the weight updater broadcasts the live Megatron parameters
to the rollout engines, and train() pushes them once right after init. init loads the reference
model (the initial student) last, into those same parameters. When A k120 resumed from iteration 39
on 11/02, rollout 40 was therefore generated by the initial student (mean response 1.7k tokens,
about 8k at the steps around it) while the actor trained from iteration 39.
"""

from types import SimpleNamespace
import unittest
from unittest.mock import MagicMock, patch

import torch

from slime.backends.megatron_utils import actor as actor_module
from slime.ray.train_actor import TrainRayActor

RESUMED, REFERENCE = 39.0, -1.0


class CpuBackuper:
    """TensorBackuper without pinned memory or CUDA synchronization."""

    def __init__(self, source_getter):
        self.source, self.saved = source_getter, {}

    @property
    def backup_tags(self):
        return list(self.saved)

    def get(self, tag):
        return self.saved[tag]

    def backup(self, tag):
        self.saved[tag] = {name: param.clone() for name, param in self.source()}

    def restore(self, tag):
        for name, param in self.source():
            param.copy_(self.saved[tag][name])


def init_resumed_actor_with_reference():
    weight = torch.zeros(2)
    args = SimpleNamespace(
        offload_train=False, debug_rollout_only=False, enable_weights_backuper=True, megatron_to_hf_mode="bridge",
        keep_old_actor=False, vocab_size=1, colocate=False, model_name="qwen3", hf_checkpoint="/student",
        rollout_data_postprocess_path=None, ref_load="/student/torch_dist", ref_ckpt_step=None,
        load="/run/checkpoints", no_load_optim=False, no_load_rng=False, finetune=False)

    def resume(args, role):
        weight.fill_(RESUMED)
        return [MagicMock()], None, None, 39

    def base_init(self, args, role, with_ref=False):
        self.args = args

    distributed = MagicMock(get_world_size=MagicMock(return_value=1), get_rank=MagicMock(return_value=0))
    with patch.object(TrainRayActor, "init", base_init), \
            patch.multiple(actor_module, monkey_patch_torch_dist=MagicMock(), init=MagicMock(),
                           is_megatron_main_rank=MagicMock(return_value=False), TrainProfiler=MagicMock(),
                           dist=distributed, get_gloo_group=MagicMock(), mpu=MagicMock(), AutoConfig=MagicMock(),
                           AutoTokenizer=MagicMock(), clear_memory=MagicMock(), Timer=MagicMock(),
                           UpdateWeightFromDistributed=MagicMock(), UpdateWeightFromTensor=MagicMock(),
                           initialize_model_and_optimizer=resume,
                           load_checkpoint=lambda *a, **k: (weight.fill_(REFERENCE), (None, None))[1],
                           named_params_and_buffers=lambda *a, **k: [("weight", weight)],
                           TensorBackuper=MagicMock(create=lambda source_getter, single_tag: CpuBackuper(source_getter))):
        actor = object.__new__(actor_module.MegatronTrainRayActor)
        start_rollout_id = actor.init(args, "actor", with_ref=True)
    return start_rollout_id, weight


class ActorResumeWeightsTests(unittest.TestCase):
    def test_parameters_after_init_are_the_resumed_policy(self):
        start_rollout_id, weight = init_resumed_actor_with_reference()
        self.assertEqual(start_rollout_id, 40)
        self.assertEqual(weight.tolist(), [RESUMED, RESUMED])


if __name__ == "__main__":
    unittest.main()
